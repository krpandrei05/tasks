CREATE OR REPLACE PROCEDURE delete_cancelled_tasks AS
BEGIN
    DELETE FROM TASKS
    WHERE status_type_id = (
        SELECT status_type_id 
        FROM STATUS_TYPES 
        WHERE status_name = 'Cancelled'
    )
    AND SYSDATE - due_date >= 3;

    COMMIT;
END;

