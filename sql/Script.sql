-- ROLES
CREATE TABLE ROLES (
	role_id NUMBER GENERATED BY DEFAULT AS IDENTITY, 
	role_name VARCHAR2(50) NOT NULL,
	CONSTRAINT roles_pk PRIMARY KEY (role_id),
	CONSTRAINT roles_name_uq UNIQUE (role_name)
);

-- PERMISIONS 
CREATE TABLE PERMISSIONS (
	permission_id NUMBER GENERATED BY DEFAULT AS IDENTITY,
	permission_action VARCHAR2(50) NOT NULL,
	resource_name VARCHAR2(50) NOT NULL,
	CONSTRAINT permissions_pk PRIMARY KEY (permission_id),
	CONSTRAINT permissios_action_resourse_uq UNIQUE (permission_action, resource_name)
);

-- ROLE_PERMISSIONS (asociativa)
CREATE TABLE ROLE_PERMISSIONS (
    role_id NUMBER NOT NULL,
    permission_id NUMBER NOT NULL,
    CONSTRAINT role_permissions_pk PRIMARY KEY (role_id, permission_id),
